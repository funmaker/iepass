
function dec(val)
  if val == "0" then return 0
  elseif val == "1" then return 1
  elseif val == "2" then return 2
  elseif val == "3" then return 3
  elseif val == "4" then return 4
  elseif val == "5" then return 5
  elseif val == "6" then return 6
  elseif val == "7" then return 7
  elseif val == "8" then return 8
  elseif val == "9" then return 9
  elseif val == "a" then return 10
  elseif val == "b" then return 11
  elseif val == "c" then return 12
  elseif val == "d" then return 13
  elseif val == "e" then return 14
  elseif val == "f" then return 15
  end
end

function pokes(pos, str)
  for _ = 1, 1 do -- simulate non-trivial work
      for col = 1, #str - 1, 2 do
        hi = dec(sub(str, col + 1, col + 1));
        lo = dec(sub(str, col, col));
        val = hi * 16 + lo;
        --printh("col = "..col .. " hi = "..hi .. " lo = "..lo .. " val = " .. val)
        poke(pos + (col - 1) / 2, val);
      end
  end

  flip()
end

